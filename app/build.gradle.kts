// "*" (default) = plain http allowed to any host, needed for a public build where every user's HA
// has a different LAN address. Set a list to lock your own build down, e.g. -Pha.cleartextHosts=homeassistant.local
val cleartextHosts: List<String> = (findProperty("ha.cleartextHosts") as String? ?: "*")
    .split(",").map { it.trim() }.filter { it.isNotEmpty() }

/** Generates res/xml/network_security_config.xml so cleartext is allowed ONLY for the listed LAN hosts. */
abstract class GenerateNetworkSecurityConfig : DefaultTask() {
    @get:Input abstract val hosts: ListProperty<String>
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val file = outputDir.get().file("xml/network_security_config.xml").asFile
        file.parentFile.mkdirs()
        val list = hosts.get()
        if (list == listOf("*")) {
            file.writeText(
                """
                |<?xml version="1.0" encoding="utf-8"?>
                |<!-- Generated. ha.cleartextHosts=* : plain http allowed (LAN Home Assistant). The app itself only
                |     ever talks to the URL set in its setup screen. -->
                |<network-security-config>
                |    <base-config cleartextTrafficPermitted="true" />
                |</network-security-config>
                |""".trimMargin()
            )
            return
        }
        val domains = list.joinToString("\n") { "        <domain includeSubdomains=\"false\">$it</domain>" }
        file.writeText(
            """
            |<?xml version="1.0" encoding="utf-8"?>
            |<!-- Generated by GenerateNetworkSecurityConfig. Edit ha.cleartextHosts in gradle.properties instead. -->
            |<network-security-config>
            |    <base-config cleartextTrafficPermitted="false" />
            |    <domain-config cleartextTrafficPermitted="true">
            |$domains
            |    </domain-config>
            |</network-security-config>
            |""".trimMargin()
        )
    }
}

val generateNsc = tasks.register<GenerateNetworkSecurityConfig>("generateNetworkSecurityConfig") {
    hosts.set(cleartextHosts)
}

// Release signing: read from a properties file OUTSIDE the repo (never committed).
// Default ~/.android-keys/hatv/signing.properties, or pass -Phatv.signing=/path/to/signing.properties
// Keys: storeFile, storePassword, keyAlias, keyPassword
val signingFile = file((findProperty("hatv.signing") as String?)
    ?: "${System.getProperty("user.home")}/.android-keys/hatv/signing.properties")
val releaseSigning: Properties? = signingFile.takeIf { it.isFile }?.let { f ->
    Properties().apply { f.inputStream().use { load(it) } }
}

android {
    namespace = "io.github.codemastervy.hatv"
    compileSdk = 34

    defaultConfig {
        applicationId = "io.github.codemastervy.hatv"
        minSdk = 26
        targetSdk = 34
        versionCode = 1
        versionName = "1.0.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        buildConfigField("String", "CLEARTEXT_HOSTS", "\"${cleartextHosts.joinToString(",")}\"")
    }

    signingConfigs {
        if (releaseSigning != null) create("release") {
            storeFile = file(releaseSigning.getProperty("storeFile"))
            storePassword = releaseSigning.getProperty("storePassword")
            keyAlias = releaseSigning.getProperty("keyAlias")
            keyPassword = releaseSigning.getProperty("keyPassword")
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            signingConfig = if (releaseSigning != null) signingConfigs.getByName("release") else {
                logger.warn("HA TV: no release key found ($signingFile); release APK is signed with the DEBUG key")
                signingConfigs.getByName("debug")
            }
        }
    }
    buildFeatures { buildConfig = true }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions { jvmTarget = "17" }
    testOptions { unitTests.isReturnDefaultValues = true }
}

androidComponents {
